// ── Cache de validation Jisho ─────────────────────────────────────────────────
const jishoCache = new Map<string, boolean>();

interface JishoResponse {
  data: {
    japanese: { word?: string; reading?: string }[];
    is_common: boolean;
  }[];
}

export async function validateWithJisho(word: string): Promise<boolean> {
  if (jishoCache.has(word)) return jishoCache.get(word)!;

  try {
    const res = await fetch(
      `https://jisho.org/api/v1/search/words?keyword=${encodeURIComponent(word)}`,
      { signal: AbortSignal.timeout(5000) }
    );
    if (!res.ok) {
      jishoCache.set(word, false);
      return false;
    }

    const json = await res.json() as JishoResponse;
    const found = json.data.some((entry) =>
      entry.japanese.some((j) => j.reading === word || j.word === word)
    );

    jishoCache.set(word, found);
    return found;
  } catch (err) {
    logger.warn('Jisho API inaccessible, validation locale uniquement', { word, err });
    return false;
  }
}

// Validation : dictionnaire local en priorité, puis Jisho
export async function isValidWordAsync(word: string): Promise<boolean> {
  if (SHIRITORI_DICTIONARY.includes(word)) return true;
  return validateWithJisho(word);
}

// Conservé pour compatibilité (synchrone, local uniquement)
export function isValidWord(word: string): boolean {
  return SHIRITORI_DICTIONARY.includes(word);
}

export function findWordStartingWith(char: string, usedWords: string[]): string | null {
  const candidates = SHIRITORI_DICTIONARY.filter(
    (w) => w.startsWith(char) && !usedWords.includes(w)
  );
  if (!candidates.length) return null;
  return candidates[Math.floor(Math.random() * candidates.length)];
}

export function getLastChar(word: string): string {
  return word[word.length - 1];
}

export function endsWithN(word: string): boolean {
  return word.endsWith('ん');
}
