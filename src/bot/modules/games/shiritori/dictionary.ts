export function isValidWord(word: string): boolean {
  return SHIRITORI_DICTIONARY.includes(word);
}

export function findWordStartingWith(char: string, usedWords: string[]): string | null {
  const candidates = SHIRITORI_DICTIONARY.filter(
    (w) => w.startsWith(char) && !usedWords.includes(w)
  );
  if (!candidates.length) return null;
  return candidates[Math.floor(Math.random() * candidates.length)];
}

export function getLastChar(word: string): string {
  return word[word.length - 1];
}

export function endsWithN(word: string): boolean {
  return word.endsWith('ん');
}
